-- Run this entire file in Supabase Dashboard > SQL Editor > New query.
-- Public visitors can read the catalog. Only dulacdatbusiness@gmail.com can add/edit/delete.
-- Do NOT put a service_role key in any website HTML.

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  platform text not null check (char_length(platform) between 1 and 80),
  cib numeric(10,2) not null default 0 check (cib >= 0),
  loose numeric(10,2) not null default 0 check (loose >= 0),
  manual numeric(10,2) not null default 0 check (manual >= 0),
  sealed numeric(10,2) not null default 0 check (sealed >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.games enable row level security;

drop policy if exists "Public can read games" on public.games;
create policy "Public can read games"
on public.games for select
to anon, authenticated
using (true);

drop policy if exists "Admin can add games" on public.games;
create policy "Admin can add games"
on public.games for insert
to authenticated
with check ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

drop policy if exists "Admin can update games" on public.games;
create policy "Admin can update games"
on public.games for update
to authenticated
using ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com')
with check ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

drop policy if exists "Admin can delete games" on public.games;
create policy "Admin can delete games"
on public.games for delete
to authenticated
using ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

grant select on public.games to anon, authenticated;
grant insert, update, delete on public.games to authenticated;
grant usage, select on sequence public.games_id_seq to authenticated;

create or replace function public.set_games_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_games_updated_at on public.games;
create trigger set_games_updated_at
before update on public.games
for each row execute function public.set_games_updated_at();
