-- DulacDat Games Buylist: Supabase database setup
-- Run this entire file in Supabase Dashboard > SQL Editor > New query.
-- Public visitors can read the catalog. Only dulacdatbusiness@gmail.com can add/edit/delete.
-- Do NOT put a service_role key in any website HTML.

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  platform text not null check (char_length(platform) between 1 and 80),
  cib numeric(10,2) not null default 0 check (cib >= 0),
  loose numeric(10,2) not null default 0 check (loose >= 0),
  manual numeric(10,2) not null default 0 check (manual >= 0),
  sealed numeric(10,2) not null default 0 check (sealed >= 0),
  cover_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Safe upgrade for an existing project that already has the games table.
alter table public.games add column if not exists cover_url text;

alter table public.games enable row level security;

drop policy if exists "Public can read games" on public.games;
create policy "Public can read games"
on public.games for select
to anon, authenticated
using (true);

drop policy if exists "Admin can add games" on public.games;
create policy "Admin can add games"
on public.games for insert
to authenticated
with check ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

drop policy if exists "Admin can update games" on public.games;
create policy "Admin can update games"
on public.games for update
to authenticated
using ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com')
with check ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

drop policy if exists "Admin can delete games" on public.games;
create policy "Admin can delete games"
on public.games for delete
to authenticated
using ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

grant select on public.games to anon, authenticated;
grant insert, update, delete on public.games to authenticated;
grant usage, select on sequence public.games_id_seq to authenticated;

create or replace function public.set_games_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_games_updated_at on public.games;
create trigger set_games_updated_at
before update on public.games
for each row execute function public.set_games_updated_at();


-- Customer buylist orders. Customers can submit, but only the admin can view/manage orders.
create table if not exists public.buylist_orders (
  id bigint generated by default as identity primary key,
  order_reference text not null unique,
  seller_email text not null check (char_length(seller_email) between 3 and 254),
  paypal_email text not null check (char_length(paypal_email) between 3 and 254),
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 100),
  estimated_total numeric(10,2) not null check (estimated_total >= 0),
  status text not null default 'pending' check (status in ('pending','received','inspected','paid','cancelled')),
  created_at timestamptz not null default now()
);

-- Safe upgrade for projects that created the orders table before order references were added.
alter table public.buylist_orders add column if not exists order_reference text;
update public.buylist_orders set order_reference = 'DD-LEGACY-' || id::text where order_reference is null;
alter table public.buylist_orders alter column order_reference set not null;
create unique index if not exists buylist_orders_order_reference_uidx on public.buylist_orders(order_reference);

alter table public.buylist_orders enable row level security;

drop policy if exists "Customers can submit buylist orders" on public.buylist_orders;
create policy "Customers can submit buylist orders"
on public.buylist_orders for insert
to anon, authenticated
with check (
  char_length(seller_email) between 3 and 254
  and char_length(paypal_email) between 3 and 254
  and jsonb_typeof(items) = 'array'
  and jsonb_array_length(items) between 1 and 100
  and estimated_total >= 0
  and status = 'pending'
);

drop policy if exists "Admin can view buylist orders" on public.buylist_orders;
create policy "Admin can view buylist orders"
on public.buylist_orders for select
to authenticated
using ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

drop policy if exists "Admin can update buylist orders" on public.buylist_orders;
create policy "Admin can update buylist orders"
on public.buylist_orders for update
to authenticated
using ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com')
with check ((auth.jwt() ->> 'email') = 'dulacdatbusiness@gmail.com');

grant insert on public.buylist_orders to anon, authenticated;
grant select, update on public.buylist_orders to authenticated;
grant usage, select on sequence public.buylist_orders_id_seq to authenticated;
